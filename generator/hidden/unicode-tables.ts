/**
 * Classes Unicode des instructions cachées : `hidden/unicode_tables.go`.
 *
 * `hidden.ts` (Secret Guard) lit cinq expressions à propriétés Unicode (`\p{…}`) ; le paquet Go `hidden` les lit dans
 * des tables explicites, calculées ici par le Node qui exécute le générateur (Node 26 : Unicode 17.0, ICU 78), sur
 * chaque point de code. Les tables ne dépendent donc pas de la version Unicode de la chaîne Go qui compile le paquet ;
 * le test Go `TestUnicodeTables` les compare aux tables de la bibliothèque standard (même version Unicode 17.0.0), et
 * le générateur des vecteurs (`main.ts`) vérifie que `hidden.ts` porte exactement ces expressions.
 *
 * `npm run hidden:tables` (dans `generator/`) réécrit le fichier ; `-- --check` compare sans rien écrire. Le test
 * Vitest `test/hidden-vectors.test.ts` le recalcule.
 */
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** Une classe : nom de la table Go et expression de `hidden.ts` (source, drapeau `u`). */
export interface HiddenUnicodeClass {
  readonly name: string;
  readonly source: string;
}

/** Les cinq expressions de `hidden.ts`, dans leur ordre d'écriture (constantes, puis l'expression de `benignInvisible`). */
export const HIDDEN_UNICODE_CLASSES: readonly HiddenUnicodeClass[] = [
  { name: 'defaultIgnorable', source: String.raw`^\p{Default_Ignorable_Code_Point}$` },
  { name: 'emoji', source: String.raw`^[\p{Extended_Pictographic}\p{Emoji_Modifier}\p{Regional_Indicator}]$` },
  { name: 'letterOrMark', source: String.raw`^[\p{L}\p{M}\p{N}]$` },
  {
    name: 'joiningScript',
    source: String.raw`^[\p{Script=Arabic}\p{Script=Syriac}\p{Script=Nko}\p{Script=Mongolian}\p{Script=Thaana}\p{Script=Hebrew}\p{Script=Devanagari}\p{Script=Bengali}\p{Script=Gurmukhi}\p{Script=Gujarati}\p{Script=Oriya}\p{Script=Tamil}\p{Script=Telugu}\p{Script=Kannada}\p{Script=Malayalam}\p{Script=Sinhala}\p{Script=Khmer}\p{Script=Myanmar}\p{M}]$`,
  },
  { name: 'mongolian', source: String.raw`^\p{Script=Mongolian}$` },
];

/** Version Unicode du Node qui exécute le générateur, écrite `X.Y.Z`. */
export function nodeUnicodeVersion(): string {
  const version = process.versions['unicode'] ?? '';
  return /^\d+\.\d+$/.test(version) ? `${version}.0` : version;
}

/** Plages fermées des points de code scalaires reconnus par l'expression (les substituts ne sont jamais lus en Go). */
export function classRanges(source: string): [number, number][] {
  const pattern = new RegExp(source, 'u');
  const ranges: [number, number][] = [];
  let open = -1;
  // Un pas de plus que U+10FFFF ferme la dernière plage ; un substitut n'est jamais membre.
  for (let codePoint = 0; codePoint <= 0x110000; codePoint += 1) {
    const scalar = codePoint <= 0x10ffff && (codePoint < 0xd800 || codePoint > 0xdfff);
    const member = scalar && pattern.test(String.fromCodePoint(codePoint));
    if (member && open < 0) open = codePoint;
    if (!member && open >= 0) {
      ranges.push([open, codePoint - 1]);
      open = -1;
    }
  }
  return ranges;
}

function hex(value: number, width: number): string {
  return `0x${value.toString(16).toUpperCase().padStart(width, '0')}`;
}

/** Table `*unicode.RangeTable` (pas 1) : plages ≤ U+FFFF dans R16, au-delà dans R32 (une plage à cheval est coupée). */
export function rangeTableGo(name: string, source: string, ranges: readonly (readonly [number, number])[]): string {
  const r16: string[] = [];
  const r32: string[] = [];
  let latinOffset = 0;
  for (const [lo, hi] of ranges) {
    if (lo <= 0xffff) {
      const top = Math.min(hi, 0xffff);
      r16.push(`\t\t{Lo: ${hex(lo, 4)}, Hi: ${hex(top, 4)}, Stride: 1},`);
      if (top <= 0xff) latinOffset += 1;
    }
    if (hi > 0xffff) r32.push(`\t\t{Lo: ${hex(Math.max(lo, 0x10000), 5)}, Hi: ${hex(hi, 5)}, Stride: 1},`);
  }
  const lines = [`// ${name} : /${source}/u de hidden.ts.`, `var ${name} = &unicode.RangeTable{`];
  if (r16.length > 0) lines.push('\tR16: []unicode.Range16{', ...r16, '\t},');
  if (r32.length > 0) lines.push('\tR32: []unicode.Range32{', ...r32, '\t},');
  if (latinOffset > 0) lines.push(`\tLatinOffset: ${String(latinOffset)},`);
  lines.push('}');
  return lines.join('\n');
}

/** Source Go de `hidden/unicode_tables.go`. */
export function buildHiddenUnicodeTablesGo(): string {
  const version = nodeUnicodeVersion();
  const tables = HIDDEN_UNICODE_CLASSES.map((entry) => rangeTableGo(entry.name, entry.source, classRanges(entry.source)));
  return [
    '// Code generated by generator/hidden/unicode-tables.ts; DO NOT EDIT.',
    '',
    `// Classes Unicode des expressions de hidden.ts (Secret Guard), calculées par Node sur chaque point de code scalaire,`,
    `// Unicode ${version}. Données Unicode : Copyright © Unicode, Inc. ; licence et avis dans UPSTREAM.md (« Tables Unicode »).`,
    '',
    'package hidden',
    '',
    'import "unicode"',
    '',
    '// unicodeTablesVersion est la version Unicode des tables de ce fichier.',
    `const unicodeTablesVersion = ${JSON.stringify(version)}`,
    '',
    ...tables.flatMap((table) => [table, '']),
  ].join('\n');
}

export const HIDDEN_UNICODE_TABLES_FILE = fileURLToPath(new URL('../../hidden/unicode_tables.go', import.meta.url));

function main(): number {
  const check = process.argv.slice(2).includes('--check');
  const unknown = process.argv.slice(2).filter((argument) => argument !== '--check');
  if (unknown.length > 0) {
    process.stderr.write('Usage : hidden:tables [--check]\n');
    return 1;
  }
  if (nodeUnicodeVersion() !== '17.0.0') {
    process.stderr.write(`Tables refusées : Node calcule Unicode ${nodeUnicodeVersion()}, attendu 17.0.0 (Node 26)\n`);
    return 1;
  }
  const source = buildHiddenUnicodeTablesGo();
  if (check) {
    let committed = '';
    try {
      committed = readFileSync(HIDDEN_UNICODE_TABLES_FILE, 'utf8');
    } catch {
      committed = '';
    }
    if (committed !== source) {
      process.stderr.write('Tables différentes : hidden/unicode_tables.go\n');
      return 1;
    }
    process.stdout.write('Tables identiques : hidden/unicode_tables.go\n');
    return 0;
  }
  writeFileSync(HIDDEN_UNICODE_TABLES_FILE, source);
  process.stdout.write('Tables écrites : hidden/unicode_tables.go\n');
  return 0;
}

if (process.argv[1] !== undefined && realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1])) {
  process.exitCode = main();
}
