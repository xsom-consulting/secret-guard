// Commande unicodetables : produit detect/unicode_tables.go, table explicite de la propriété Unicode
// Default_Ignorable_Code_Point (absente de RE2), depuis le fichier DerivedCoreProperties.txt d'une version Unicode
// figée.
//
// Le fichier Unicode n'est pas dans le dépôt : le télécharger dans un répertoire temporaire, puis, à la racine du
// dépôt,
//
//	go run ./tools/unicodetables <DerivedCoreProperties.txt> > detect/unicode_tables.go
//
// Son SHA-256 et sa version sont vérifiés avant toute écriture ; tout écart arrête la commande sans rien écrire.
// Source : https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt (UPSTREAM.md, « Tables Unicode »).
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"os"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

const (
	// UnicodeVersion est la version des données lues ; celle de Node 26 (ICU 78) et de golang.org/x/text sous Go 1.27.
	UnicodeVersion = "17.0.0"
	// SourceSHA256 est le SHA-256 de DerivedCoreProperties.txt 17.0.0.
	SourceSHA256 = "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"
	property     = "Default_Ignorable_Code_Point"
)

// Range est une plage fermée de points de code.
type Range struct{ Lo, Hi rune }

func main() {
	if len(os.Args) != 2 {
		_, _ = fmt.Fprintln(os.Stderr, "usage : go run ./tools/unicodetables <DerivedCoreProperties.txt>")
		os.Exit(2)
	}
	data, err := os.ReadFile(os.Args[1])
	if err == nil {
		var out []byte
		out, err = Generate(data)
		if err == nil {
			_, err = os.Stdout.Write(out)
		}
	}
	if err != nil {
		_, _ = fmt.Fprintf(os.Stderr, "unicodetables : %v\n", err)
		os.Exit(1)
	}
}

// Generate vérifie le fichier Unicode et rend le source Go de la table.
func Generate(data []byte) ([]byte, error) {
	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != SourceSHA256 {
		return nil, fmt.Errorf("SHA-256 inattendu %s (attendu %s, DerivedCoreProperties.txt %s)", got, SourceSHA256, UnicodeVersion)
	}
	if !bytes.HasPrefix(data, []byte("# DerivedCoreProperties-"+UnicodeVersion+".txt")) {
		return nil, errors.New("en-tête de version absent")
	}
	ranges, err := Parse(bytes.NewReader(data), property)
	if err != nil {
		return nil, err
	}
	return Render(ranges), nil
}

// Parse lit les lignes « XXXX(..YYYY)? ; <propriété> » et rend les plages triées et fusionnées.
func Parse(r io.Reader, name string) ([]Range, error) {
	var ranges []Range
	scanner := bufio.NewScanner(r)
	for line := 1; scanner.Scan(); line++ {
		text := scanner.Text()
		if i := strings.IndexByte(text, '#'); i >= 0 {
			text = text[:i]
		}
		fields := strings.Split(text, ";")
		if len(fields) < 2 || strings.TrimSpace(fields[1]) != name {
			continue
		}
		lo, hi, ok := strings.Cut(strings.TrimSpace(fields[0]), "..")
		if !ok {
			hi = lo
		}
		l, err1 := strconv.ParseUint(lo, 16, 32)
		h, err2 := strconv.ParseUint(hi, 16, 32)
		if err1 != nil || err2 != nil || l > h || h > 0x10FFFF {
			return nil, fmt.Errorf("ligne %d : plage illisible", line)
		}
		ranges = append(ranges, Range{rune(l), rune(h)})
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	if len(ranges) == 0 {
		return nil, fmt.Errorf("propriété %s absente", name)
	}
	sort.Slice(ranges, func(i, j int) bool { return ranges[i].Lo < ranges[j].Lo })
	merged := ranges[:1]
	for _, next := range ranges[1:] {
		last := &merged[len(merged)-1]
		if next.Lo <= last.Hi+1 {
			last.Hi = max(last.Hi, next.Hi)
			continue
		}
		merged = append(merged, next)
	}
	return merged, nil
}

// Render écrit le fichier Go (gofmt) : une unicode.RangeTable de pas 1, plages 16 bits puis 32 bits.
func Render(ranges []Range) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by tools/unicodetables; DO NOT EDIT.

// Propriété Unicode %s, version %s, lue dans DerivedCoreProperties.txt
// (SHA-256 %s ; https://www.unicode.org/Public/%s/ucd/).
// Données Unicode : Copyright © Unicode, Inc. ; licence et avis dans UPSTREAM.md (« Tables Unicode »).

package detect

import "unicode"

// unicodeTablesVersion est la version Unicode de defaultIgnorableCodePoint.
const unicodeTablesVersion = %q

// defaultIgnorableCodePoint est la propriété %s (RE2 n'a pas \p{%s}).
var defaultIgnorableCodePoint = &unicode.RangeTable{
	R16: []unicode.Range16{
`, property, UnicodeVersion, SourceSHA256, UnicodeVersion, UnicodeVersion, property, property)
	var r32 []Range
	latin := 0
	for _, r := range ranges {
		if r.Hi > 0xFFFF {
			if r.Lo <= 0xFFFF {
				fmt.Fprintf(&b, "\t\t{Lo: 0x%04X, Hi: 0xFFFF, Stride: 1},\n", r.Lo)
				r.Lo = 0x10000
			}
			r32 = append(r32, r)
			continue
		}
		if r.Hi <= unicode.MaxLatin1 {
			latin++
		}
		fmt.Fprintf(&b, "\t\t{Lo: 0x%04X, Hi: 0x%04X, Stride: 1},\n", r.Lo, r.Hi)
	}
	b.WriteString("\t},\n\tR32: []unicode.Range32{\n")
	for _, r := range r32 {
		fmt.Fprintf(&b, "\t\t{Lo: 0x%05X, Hi: 0x%05X, Stride: 1},\n", r.Lo, r.Hi)
	}
	fmt.Fprintf(&b, "\t},\n\tLatinOffset: %d,\n}\n", latin)
	return b.Bytes()
}
